// Only recognized UI sentence structures are matched; captured custom names are preserved.
const known = text => messages[text] || text;
const phase = text => known(text).replace(/^(Move clear \/|Approach \/|At) (ice outlet|coffee outlet|milk-tea outlet|plastic lid applicator|paper lid dispenser)$/, (_, action, outlet) => ({'Move clear /':'移至安全位置／','Approach /':'接近／','At':'到达'}[action]) + ({'ice outlet':'出冰口','coffee outlet':'咖啡出口','milk-tea outlet':'奶茶出口','plastic lid applicator':'塑料杯盖扣盖机','paper lid dispenser':'出纸盖器'}[outlet]));
const translatePhase = text => {
  const translated = phase(text);
  if (translated !== text) return translated;
  if (text.includes(' · ')) return text.split(' · ').map(translatePhase).join(' · ');
  const paired = text.match(/^(.+) \/ (Bread: .+|Bread Nova-5 stationary)$/);
  if (paired) return translatePhase(paired[1]) + '／' + translatePhase(paired[2]);
  return text;
};
const detail = text => {
  if (Object.hasOwn(messages, text)) return messages[text];
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
};

